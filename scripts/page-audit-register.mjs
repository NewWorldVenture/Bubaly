#!/usr/bin/env node
// Page audit register — one row per page route, one file per lane.
//
// WHY LANES, AND WHY FILES. Several agents (Claude sessions and Codex) audit
// the site at once. If they all edited one table they would conflict on every
// push, and the last rebase would silently drop someone's rows (it has
// happened: docs/audit/COORDINATION.md §1, agent-05's note). So each lane is its
// own file under docs/audit/pages/, a lane is claimed before it is worked, and
// an agent edits only the lane it holds. finalaudit.md carries the roll-up,
// and that roll-up is GENERATED from the lane files — so resolving a conflict
// in it is never a merge, it is re-running this script.
//
//   node scripts/page-audit-register.mjs          # check: exit 1 if stale
//   node scripts/page-audit-register.mjs --write  # add new routes, drop gone
//                                                 # ones, rewrite the roll-up
//
// What --write never does is change a row's Status, Checked, By or Notes:
// those belong to whoever audited the page. New routes arrive as UNAUDITED,
// routes whose page.tsx is gone are removed and reported.

import { execSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = new URL('..', import.meta.url).pathname;
const DIR = join(ROOT, 'docs/audit/pages');
const FINAL = join(ROOT, 'finalaudit.md');
const START = '<!-- page-register:start — generated by scripts/page-audit-register.mjs; edit the lane files, not this -->';
const END = '<!-- page-register:end -->';

export const STATUSES = ['UNAUDITED', 'IN PROGRESS', 'PASS', 'FIXED', 'OPEN', 'BLOCKED'];

/**
 * Lanes, in match order: the first whose test accepts the route wins, so the
 * specific ones come before the catch-alls. `unit` is the A-unit in
 * docs/audit/COORDINATION.md §2 that owns the same paths, so a page claim and
 * a code claim never point two agents at one file.
 */
export const LANES = [
  { id: 'PUBLIC', unit: 'A-17', title: 'Public marketing, legal and share pages', test: (f) => f.startsWith('app/(marketing)/') || /^app\/(s|gift|pay|join|reviews|offline)\//.test(f) || f === 'app/page.tsx' },
  { id: 'AUTH', unit: 'A-03/A-04', title: 'Sign-in, sign-up, kid login, onboarding', test: (f) => f.startsWith('app/(auth)/') || f.startsWith('app/auth/') || f.startsWith('app/(app)/auth/') || f.startsWith('app/onboarding/') },
  { id: 'ADMIN', unit: 'A-17', title: 'Super-admin console', test: (f) => f.startsWith('app/(app)/admin/') },
  { id: 'MARKETPLACE', unit: 'A-14', title: 'Marketplace', test: (f) => f.startsWith('app/(app)/marketplace/') },
  { id: 'MONEY', unit: 'A-07/A-08/A-09', title: 'Wallet, economy, missions, kids and parent views, billing', test: (f) => /^app\/\(app\)\/(wallet|economy|missions|kids|parent)\//.test(f) || /^app\/\(app\)\/dashboard\/(billing|budget|finances|money[^/]*|subscriptions|bills|savings[^/]*|tax[^/]*|invest[^/]*|allowance[^/]*)(\/|$)/.test(f) },
  { id: 'TRAVEL', unit: 'A-13', title: 'Vacations, trips, concierge, trip intel', test: (f) => /^app\/\(app\)\/dashboard\/(vacations|trips|concierge|trip-intel|weekend)(\/|$)/.test(f) },
  { id: 'SOCIAL', unit: 'A-17', title: 'Social publishing', test: (f) => f.startsWith('app/(app)/dashboard/social/') },
  { id: 'FAMILY', unit: 'A-12', title: 'Family, guardian, safety, members', test: (f) => /^app\/\(app\)\/(family|guardian)\//.test(f) || f.startsWith('app/(app)/dashboard/family/') },
  { id: 'HOME', unit: 'A-05', title: 'Home, display, capture and the app shell pages', test: (f) => /^app\/\(app\)\/(home|display|capture|services|referrals|feedback)\//.test(f) || /^app\/\(app\)\/dashboard\/page\.tsx$/.test(f) || f.startsWith('app/(app)/dashboard/home/') },
  { id: 'DASH-A-F', unit: 'A-05..A-11', title: 'Dashboard modules a–f', test: (f) => /^app\/\(app\)\/dashboard\/[a-f]/.test(f) },
  { id: 'DASH-G-M', unit: 'A-05..A-11', title: 'Dashboard modules g–m', test: (f) => /^app\/\(app\)\/dashboard\/[g-m]/.test(f) },
  { id: 'DASH-N-Z', unit: 'A-05..A-11', title: 'Dashboard modules n–z', test: (f) => /^app\/\(app\)\/dashboard\/[n-z0-9]/.test(f) },
  { id: 'OTHER', unit: '—', title: 'Anything no lane above claims (should stay empty)', test: () => true },
];

/** `app/(app)/dashboard/meals/[id]/page.tsx` → `/dashboard/meals/[id]`. */
export function routeOf(file) {
  const path = file.replace(/^app\//, '').replace(/(^|\/)page\.tsx$/, '');
  const route = path.split('/').filter((s) => s && !/^\(.*\)$/.test(s)).join('/');
  return `/${route}`;
}

export function pageFiles() {
  return execSync("git ls-files 'app/**/page.tsx' 'app/page.tsx'", { cwd: ROOT, encoding: 'utf8' })
    .split('\n').filter(Boolean).sort();
}

export function laneOf(file) {
  return LANES.find((lane) => lane.test(file));
}

const HEADER = '| Route | Source | Status | Checked (UTC) | By | Notes |';
const RULE = '|---|---|---|---|---|---|';

/** Rows already in a lane file, keyed by source path, so --write keeps them. */
export function readRows(text) {
  const rows = new Map();
  for (const line of text.split('\n')) {
    const m = line.match(/^\| `([^`]*)` \| `([^`]*)` \| ([^|]*) \| ([^|]*) \| ([^|]*) \| (.*) \|$/);
    if (!m) continue;
    rows.set(m[2], { route: m[1], file: m[2], status: m[3].trim(), checked: m[4].trim(), by: m[5].trim(), notes: m[6].trim() });
  }
  return rows;
}

const row = (r) => `| \`${r.route}\` | \`${r.file}\` | ${r.status} | ${r.checked || '—'} | ${r.by || '—'} | ${r.notes || ''} |`;

function laneFile(lane) {
  return join(DIR, `${lane.id}.md`);
}

function laneText(lane, rows, claims) {
  return [
    `# Page audit lane ${lane.id} — ${lane.title}`,
    '',
    `Owning unit (docs/audit/COORDINATION.md §2): **${lane.unit}**. Protocol: docs/audit/pages/README.md.`,
    '',
    '## Claim',
    '',
    claims.trim() || '| Agent | Claimed (UTC) | Heartbeat (UTC) | State |\n|---|---|---|---|\n| — | — | — | FREE |',
    '',
    '## Pages',
    '',
    HEADER,
    RULE,
    ...rows.map(row),
    '',
  ].join('\n');
}

function claimsOf(text) {
  const m = text.match(/## Claim\n\n([\s\S]*?)\n\n## Pages/);
  return m ? m[1] : '';
}

/** Build every lane from the tree, carrying audited fields forward. */
export function build() {
  const byLane = new Map(LANES.map((l) => [l.id, []]));
  for (const file of pageFiles()) byLane.get(laneOf(file).id).push(file);
  const lanes = [];
  const removed = [];
  for (const lane of LANES) {
    const path = laneFile(lane);
    const existing = existsSync(path) ? readFileSync(path, 'utf8') : '';
    const old = readRows(existing);
    const files = byLane.get(lane.id);
    const rows = files.map((file) => old.get(file) ?? { route: routeOf(file), file, status: 'UNAUDITED', checked: '', by: '', notes: '' });
    for (const r of rows) r.route = routeOf(r.file);
    for (const f of old.keys()) if (!files.includes(f)) removed.push(`${lane.id}: ${f}`);
    if (!files.length && !existing) continue;
    lanes.push({ lane, rows, text: laneText(lane, rows, claimsOf(existing)), path, existing });
  }
  return { lanes, removed };
}

export function rollup(lanes) {
  const all = lanes.flatMap((l) => l.rows.map((r) => ({ ...r, lane: l.lane.id })));
  const count = (rows, s) => rows.filter((r) => r.status === s).length;
  const lines = [
    START,
    '',
    `**${all.length} pages** — one row per \`page.tsx\`, grouped by lane. Status is set in the lane files under \`docs/audit/pages/\` by the agent holding the lane; this table is regenerated from them (\`node scripts/page-audit-register.mjs --write\`) and \`tests/every-page-is-in-the-page-register.test.ts\` fails if it is stale or a page is missing.`,
    '',
    '| Lane | Pages | UNAUDITED | IN PROGRESS | PASS | FIXED | OPEN | BLOCKED |',
    '|---|---|---|---|---|---|---|---|',
    ...lanes.map((l) => `| [${l.lane.id}](docs/audit/pages/${l.lane.id}.md) | ${l.rows.length} | ${STATUSES.map((s) => count(l.rows, s)).join(' | ')} |`),
    `| **Total** | **${all.length}** | ${STATUSES.map((s) => `**${count(all, s)}**`).join(' | ')} |`,
    '',
    '<details><summary>Every page, with its status</summary>',
    '',
    '| Lane | Route | Status | Checked (UTC) | By | Notes |',
    '|---|---|---|---|---|---|',
    ...all.map((r) => `| ${r.lane} | \`${r.route}\` | ${r.status} | ${r.checked || '—'} | ${r.by || '—'} | ${r.notes || ''} |`),
    '',
    '</details>',
    '',
    END,
  ];
  return lines.join('\n');
}

function main() {
  const write = process.argv.includes('--write');
  const { lanes, removed } = build();
  const bad = lanes.flatMap((l) => l.rows.filter((r) => !STATUSES.includes(r.status)).map((r) => `${l.lane.id} ${r.route}: "${r.status}"`));
  if (bad.length) {
    console.error(`Unknown status (use one of ${STATUSES.join(', ')}):\n  ${bad.join('\n  ')}`);
    process.exit(1);
  }
  const final = readFileSync(FINAL, 'utf8');
  const section = rollup(lanes);
  const hasSection = final.includes(START) && final.includes(END);
  const nextFinal = hasSection
    ? final.slice(0, final.indexOf(START)) + section + final.slice(final.indexOf(END) + END.length)
    : null;
  const stale = lanes.filter((l) => l.text !== l.existing).map((l) => l.path.replace(ROOT, ''));
  if (!hasSection || nextFinal !== final) stale.push('finalaudit.md (page register section)');

  if (!write) {
    if (stale.length) {
      console.error(`Page register is stale:\n  ${stale.join('\n  ')}\nRun: node scripts/page-audit-register.mjs --write`);
      process.exit(1);
    }
    console.log(`Page register current: ${lanes.reduce((n, l) => n + l.rows.length, 0)} pages in ${lanes.length} lanes.`);
    return;
  }
  mkdirSync(DIR, { recursive: true });
  for (const l of lanes) if (l.text !== l.existing) writeFileSync(l.path, l.text);
  if (!hasSection) {
    console.error(`finalaudit.md has no page-register markers. Add\n${START}\n${END}\nwhere the section belongs, then re-run.`);
    process.exit(1);
  }
  if (nextFinal !== final) writeFileSync(FINAL, nextFinal);
  if (removed.length) console.log(`Removed (page.tsx no longer exists):\n  ${removed.join('\n  ')}`);
  console.log(`Wrote ${stale.length} file(s); ${lanes.reduce((n, l) => n + l.rows.length, 0)} pages in ${lanes.length} lanes.`);
}

if (import.meta.url === `file://${process.argv[1]}`) main();
