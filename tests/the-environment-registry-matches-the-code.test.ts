import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';
import { JSON_PATH, MD_PATH, buildRegistry } from '../scripts/environment-registry.mjs';

/**
 * THE ENVIRONMENT REGISTRY MATCHES THE CODE.
 *
 * docs/architecture/environment-registry.{json,md} used to be written by hand.
 * An audit found 343 of its 423 file:line citations no longer matched the code,
 * and it called variables "unverified" whose readers were one grep away. It is
 * now generated by scripts/environment-registry.mjs, and this test regenerates
 * it in memory: a new process.env read, a moved line or a template edit fails
 * here until `npm run env:registry` is rerun and the result committed.
 *
 * It also holds .env.example to the template rule the registry prints: every
 * variable the app, the build, the mobile app or an operator script reads is
 * declared once, and every secret-grade one says [secret]. This scanner sees
 * the reads the dotted-name coverage tests cannot: credentialEnv tables read by
 * a computed key, process.env aliases, destructuring, and workflow env blocks.
 */

type Variable = {
  name: string;
  tier: string;
  secret: boolean;
  templateRequired: boolean;
  declarations: { path: string; line: number; live: boolean; purpose: string }[];
  readers: string[];
};
type Registry = {
  checks: { missingFromTemplate: string[]; duplicateDeclarations: string[]; declaredButUnread: string[]; secretsNotTagged: string[] };
  variables: Variable[];
};

let built: { json: string; markdown: string; registry: Registry };
const variable = (name: string): Variable => {
  const v = built.registry.variables.find((x) => x.name === name);
  expect(v, `${name} is in the registry`).toBeDefined();
  return v as Variable;
};

beforeAll(() => {
  built = buildRegistry(process.cwd()) as typeof built;
}, 60_000);

describe('the committed environment registry is the generated one', () => {
  it('the JSON matches a fresh scan (run `npm run env:registry` if not)', () => {
    expect(readFileSync(JSON_PATH, 'utf8') === built.json, `${JSON_PATH} is stale: run npm run env:registry`).toBe(true);
  });

  it('the Markdown matches a fresh scan (run `npm run env:registry` if not)', () => {
    expect(readFileSync(MD_PATH, 'utf8') === built.markdown, `${MD_PATH} is stale: run npm run env:registry`).toBe(true);
  });

  it('makes no claim it did not scan for', () => {
    expect(built.json).not.toMatch(/unverified|PARTIAL_STATIC_INVENTORY/i);
    // No email address of any kind is copied out of code or templates.
    expect(built.json).not.toMatch(/[A-Za-z0-9._%+-]+@[A-Za-z0-9-]+\.[A-Za-z]/);
  });
});

describe('the scanner sees every kind of read (guards the guard)', () => {
  it('a dotted read in lib', () => {
    expect(variable('SUPABASE_SERVICE_ROLE_KEY').readers).toContain('lib/supabase/server.ts:77');
  });

  it('a name listed in a credentialEnv table and read by a computed key', () => {
    expect(variable('FACEBOOK_APP_SECRET').readers.some((r) => r.startsWith('lib/social/capabilities.ts:') && r.endsWith('(listed-for-dynamic-read)'))).toBe(true);
  });

  it('a read through an injectable env parameter', () => {
    expect(variable('AI_PROVIDER_STUB').readers.some((r) => r.startsWith('lib/ai/provider-stub.ts:'))).toBe(true);
    expect(variable('AI_PROVIDER_STUB').tier).toBe('app');
  });

  it('the mobile app, the native shell build and an operator script', () => {
    expect(variable('EXPO_PUBLIC_API_URL').tier).toBe('mobile');
    expect(variable('CAP_SERVER_URL').tier).toBe('build');
    expect(variable('TEST_EMAIL').tier).toBe('operator-scripts');
  });

  it('a workflow env binding', () => {
    expect(variable('E2E_DURABLE_SESSION').readers.some((r) => r.startsWith('.github/workflows/ci.yml:'))).toBe(true);
  });

  it('a name only tests set is not mistaken for one the code reads', () => {
    expect(variable('FCM_SERVER_KEY').readers).toEqual([]);
  });
});

describe('.env.example follows the template rule', () => {
  it('declares every variable read outside tests and CI', () => {
    expect(built.registry.checks.missingFromTemplate).toEqual([]);
  });

  it('declares no variable twice', () => {
    expect(built.registry.checks.duplicateDeclarations).toEqual([]);
  });

  it('declares nothing that no code reads', () => {
    expect(built.registry.checks.declaredButUnread).toEqual([]);
  });

  it('tags every secret-grade declaration [secret]', () => {
    expect(built.registry.checks.secretsNotTagged).toEqual([]);
  });

  it('gives every app-tier declaration a purpose', () => {
    const silent = built.registry.variables
      .filter((v) => v.tier === 'app' && v.declarations.some((d) => d.path === '.env.example' && d.purpose === ''))
      .map((v) => v.name);
    expect(silent).toEqual([]);
  });
});

describe('the template rule catches a new read (fixture tree)', () => {
  let root = '';
  beforeAll(() => {
    root = mkdtempSync(join(tmpdir(), 'env-registry-'));
    mkdirSync(join(root, 'lib'), { recursive: true });
    writeFileSync(join(root, 'lib', 'feature.ts'), [
      'export const a = process.env.DECLARED_FLAG;',
      "export const b = process.env['UNDECLARED_FLAG'] ?? 'off';",
      'const { DESTRUCTURED_KEY } = process.env;',
      'export const c = DESTRUCTURED_KEY;',
      '// process.env.ONLY_IN_A_COMMENT',
      "export const d = 'process.env.ONLY_IN_A_STRING';",
      '',
    ].join('\n'));
    writeFileSync(join(root, '.env.example'), '# Declared.\nDECLARED_FLAG=\n# [secret] Declared twice.\nTWICE_SECRET=\n# TWICE_SECRET=\n');
  });
  afterAll(() => rmSync(root, { recursive: true, force: true }));

  it('reports exactly the undeclared reads, and the duplicate', () => {
    const { registry } = buildRegistry(root) as { registry: Registry };
    expect(registry.checks.missingFromTemplate).toEqual(['DESTRUCTURED_KEY', 'UNDECLARED_FLAG']);
    expect(registry.checks.duplicateDeclarations).toEqual(['TWICE_SECRET (.env.example:4, .env.example:5)']);
    expect(registry.checks.declaredButUnread).toEqual(['TWICE_SECRET']);
    const undeclared = registry.variables.find((v) => v.name === 'UNDECLARED_FLAG') as Variable & { facts: { kind: string; value?: string }[] };
    expect(undeclared.readers).toEqual(['lib/feature.ts:2 (read-indexed)']);
    expect(undeclared.facts).toContainEqual(expect.objectContaining({ kind: 'fallback-literal', value: 'off' }));
    expect(registry.variables.map((v) => v.name)).not.toContain('ONLY_IN_A_COMMENT');
    expect(registry.variables.map((v) => v.name)).not.toContain('ONLY_IN_A_STRING');
  });
});
